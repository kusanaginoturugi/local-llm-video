def parse():
    sections = []
    lines = []
    for raw in DIALOGUE.strip().splitlines():
        if raw.startswith("# "):
            sections.append((len(lines) + 1, raw[2:]))
            continue
        speaker, text = raw.split("\t", 1)
        lines.append((speaker, text))
    return lines, sections


def main():
    lines, _ = parse()
    with (HERE / "script.tsv").open("w", newline="") as f:
        writer = csv.writer(f, delimiter="\t", lineterminator="\n")
        writer.writerow(("no", "speaker", "text"))
        writer.writerows((i, speaker, text) for i, (speaker, text) in enumerate(lines, 1))


if __name__ == "__main__":
    main()
