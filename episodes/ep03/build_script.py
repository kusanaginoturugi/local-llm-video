def first(text, n):
    """返事の先頭 n 文（読み上げる分）。"""
    out, buf = [], ""
    for ch in text.replace("\n", ""):
        buf += ch
        if ch in "。！？":
            out.append(buf.strip())
            buf = ""
        if len(out) == n:
            break
    # 絵文字は読み上げない（voice-chat も声にする前に落とす）
    return re.sub(r"[\U0001F000-\U0001FFFF\u2600-\u27BF]", "", "".join(out))


