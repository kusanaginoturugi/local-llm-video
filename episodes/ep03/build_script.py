def main():
    rows, screens = [], []
    for section, lines in SECTIONS:
        for speaker, text, screen in lines:
            no = len(rows) + 1
            rows.append((no, speaker, text))
            screens.append((no, section, speaker, screen))
    with open(os.path.join(HERE, "script.tsv"), "w", newline="") as f:
        w = csv.writer(f, delimiter="\t", lineterminator="\n")
        w.writerow(["no", "speaker", "text"])
        w.writerows(rows)
    with open(os.path.join(HERE, "screens.tsv"), "w", newline="") as f:
        w = csv.writer(f, delimiter="\t", lineterminator="\n")
        w.writerow(["no", "section", "speaker", "screen"])
        w.writerows(screens)
    print(f"{len(rows)} 行")


if __name__ == "__main__":
    main()
